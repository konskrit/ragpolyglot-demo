#!/usr/bin/env node
/**
 * Generate TS / C# / Go wire types from libs/contracts/schemas/wire.schema.json via quicktype,
 * plus shared Rabbit routing keys from routing-keys.json.
 * Usage: node libs/contracts/generate.mjs
 * Check: node libs/contracts/generate.mjs --check
 */
import { execFileSync } from 'node:child_process';
import {
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
  mkdirSync,
  existsSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '../..');
const schema = join(__dirname, 'schemas/wire.schema.json');
const routingKeysPath = join(__dirname, 'schemas/routing-keys.json');
const quicktypeBin = join(root, 'node_modules/quicktype/dist/index.js');
const check = process.argv.includes('--check');

const outputs = {
  ts: join(root, 'libs/shared/src/lib/generated/wire.ts'),
  cs: join(root, 'apps/document-service/Contracts/Wire.g.cs'),
  go: join(root, 'apps/rag-worker/models/wire_gen.go'),
  routingTs: join(root, 'libs/shared/src/lib/generated/routing.ts'),
  routingCs: join(root, 'apps/document-service/Contracts/WireRoutingKeys.g.cs'),
  routingGo: join(root, 'apps/rag-worker/rabbitmq/routing_gen.go'),
};

const header = (lang, from = 'wire.schema.json') => {
  const line = `Code generated by libs/contracts/generate.mjs from ${from}. DO NOT EDIT.`;
  if (lang === 'ts') return `/* ${line} */\n\n`;
  if (lang === 'cs')
    return `// <auto-generated/>\n// ${line}\n#nullable enable\n#pragma warning disable CS8618\n\n`;
  return `// ${line}\n\n`;
};

function runQuicktype(args, outFile) {
  execFileSync(process.execPath, [quicktypeBin, ...args, '-o', outFile], {
    stdio: 'pipe',
    cwd: root,
  });
  return readFileSync(outFile, 'utf8');
}

function stripContractsBundleGo(src) {
  return src.replace(/type ContractsBundle struct \{[\s\S]*?\n\}\n*/, '');
}

function stripContractsBundleCs(src) {
  return src
    .replace(/\s*\/\/\/ <summary>[\s\S]*?<\/summary>\s*/g, '\n')
    .replace(
      /\n\s*public partial class ContractsBundle\s*\{[\s\S]*?\n\s*\}\s*/m,
      '\n',
    );
}

function stripContractsBundleTs(src) {
  return src
    .replace(/\/\*\*[\s\S]*?\*\/\s*(?=export interface ContractsBundle\b)/, '')
    .replace(/export interface ContractsBundle\s*\{[\s\S]*?\}\n*/, '');
}

function postprocessGo(src) {
  let body = stripContractsBundleGo(src)
    .replaceAll('DocumentIDS', 'DocumentIDs')
    .replace(/\bint64\b/g, 'int')
    .replace(/\*int64\b/g, '*int');

  const imports = new Set();
  body = body.replace(/^import\s+\([\s\S]*?\)\s*$/gm, (block) => {
    for (const m of block.matchAll(/"([^"]+)"/g)) imports.add(m[1]);
    return '';
  });
  body = body.replace(/^import\s+"([^"]+)"\s*$/gm, (_, mod) => {
    imports.add(mod);
    return '';
  });
  body = body.replace(/^package\s+\w+\s*$/gm, '');
  body = body.replace(/^\n+/, '');

  const importBlock =
    imports.size === 0
      ? ''
      : imports.size === 1
        ? `import "${[...imports][0]}"\n\n`
        : `import (\n${[...imports]
            .sort()
            .map((m) => `\t"${m}"`)
            .join('\n')}\n)\n\n`;

  return `package models\n\n${importBlock}${body}`;
}

function postprocessCs(src) {
  return stripContractsBundleCs(src)
    .replace(/\bDateTimeOffset\b/g, 'DateTime')
    .replace(/\blong\?/g, 'int?')
    .replace(/\blong\b/g, 'int');
}

function postprocessTs(src) {
  const body = stripContractsBundleTs(src);
  return `${body}\n/** @deprecated Prefer SearchHit — kept for existing imports. */\nexport type RagSearchHit = SearchHit;\n`;
}

function loadRoutingKeys() {
  const rows = JSON.parse(readFileSync(routingKeysPath, 'utf8'));
  if (!Array.isArray(rows) || rows.length === 0) {
    throw new Error('routing-keys.json must be a non-empty array');
  }
  for (const row of rows) {
    if (!row?.name || !row?.key) {
      throw new Error('routing-keys.json entries need name + key');
    }
  }
  return rows;
}

function generateRouting(rows) {
  const tsEntries = rows.map((r) => `  ${r.name}: '${r.key}',`).join('\n');
  const routingTs =
    header('ts', 'routing-keys.json') +
    `export const WIRE_ROUTING_KEYS = {\n${tsEntries}\n} as const;\n\n` +
    `export type WireRoutingKey =\n  (typeof WIRE_ROUTING_KEYS)[keyof typeof WIRE_ROUTING_KEYS];\n\n` +
    `export const WIRE_ROUTING_KEY_LIST = Object.values(WIRE_ROUTING_KEYS);\n`;

  const csConsts = rows
    .map((r) => `    public const string ${r.name} = "${r.key}";`)
    .join('\n');
  const routingCs =
    header('cs', 'routing-keys.json') +
    `namespace DocumentService.Contracts;\n\n` +
    `public static class WireRoutingKeys\n{\n${csConsts}\n}\n`;

  const goConsts = rows
    .map((r) => `\tRouting${r.name} = "${r.key}"`)
    .join('\n');
  const routingGo =
    header('go', 'routing-keys.json') +
    `package rabbitmq\n\n` +
    `const (\n${goConsts}\n)\n`;

  return { routingTs, routingCs, routingGo };
}

function generateWire(dir) {
  mkdirSync(dir, { recursive: true });
  const tsRaw = runQuicktype(
    [
      '--src-lang',
      'schema',
      '--src',
      schema,
      '--lang',
      'ts',
      '--just-types',
      '--no-date-times',
      '--top-level',
      'ContractsBundle',
    ],
    join(dir, 'wire.ts'),
  );
  const csRaw = runQuicktype(
    [
      '--src-lang',
      'schema',
      '--src',
      schema,
      '--lang',
      'cs',
      '--just-types',
      '--framework',
      'SystemTextJson',
      '--csharp-version',
      '8',
      '--namespace',
      'DocumentService.Contracts',
      '--top-level',
      'ContractsBundle',
    ],
    join(dir, 'Wire.g.cs'),
  );
  const goRaw = runQuicktype(
    [
      '--src-lang',
      'schema',
      '--src',
      schema,
      '--lang',
      'go',
      '--just-types',
      '--package',
      'models',
      '--omit-empty',
      '--top-level',
      'ContractsBundle',
    ],
    join(dir, 'wire_gen.go'),
  );

  return {
    ts: header('ts') + postprocessTs(tsRaw),
    cs: header('cs') + postprocessCs(csRaw),
    go: header('go') + postprocessGo(goRaw),
  };
}

function gofmt(path) {
  try {
    execFileSync('gofmt', ['-w', path], { stdio: 'pipe' });
  } catch (err) {
    console.error(
      'gofmt is required for contracts:gen/check (install Go and ensure gofmt is on PATH).',
    );
    throw err;
  }
}

function normalizeEol(text) {
  return text.replace(/\r\n/g, '\n');
}

function writeOutputs(files) {
  for (const [key, path] of Object.entries(outputs)) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, normalizeEol(files[key]), 'utf8');
  }
}

const tmp = mkdtempSync(join(tmpdir(), 'rag-contracts-'));
try {
  const wire = generateWire(tmp);
  const goTmp = join(tmp, 'wire_gen.go');
  writeFileSync(goTmp, wire.go, 'utf8');
  gofmt(goTmp);
  wire.go = readFileSync(goTmp, 'utf8');

  const routing = generateRouting(loadRoutingKeys());
  const routingGoTmp = join(tmp, 'routing_gen.go');
  writeFileSync(routingGoTmp, routing.routingGo, 'utf8');
  gofmt(routingGoTmp);
  routing.routingGo = readFileSync(routingGoTmp, 'utf8');

  const files = { ...wire, ...routing };

  // Stabilize cross-OS compares (gofmt/read may reintroduce \r\n on Windows).
  for (const key of Object.keys(files)) {
    files[key] = normalizeEol(files[key]);
  }

  if (check) {
    for (const [key, path] of Object.entries(outputs)) {
      if (!existsSync(path)) {
        console.error(`missing generated file: ${path}`);
        process.exit(1);
      }
      const existing = normalizeEol(readFileSync(path, 'utf8'));
      if (existing !== files[key]) {
        console.error(`generated contracts drift: ${path}`);
        console.error('Run: npm run contracts:gen');
        console.error(
          '(Do not run Prettier on generated files — see .prettierignore.)',
        );
        process.exit(1);
      }
    }
    console.log('contracts:check ok');
  } else {
    writeOutputs(files);
    console.log('generated:');
    for (const path of Object.values(outputs)) console.log(`  ${path}`);
  }
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
